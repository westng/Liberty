import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaBase = path.join(repositoryRoot, "packages/shared-types/schemas");
const defaultOutputDirectory = path.join(repositoryRoot, "packages/shared-types/src/generated");
const outputIndex = process.argv.indexOf("--output-dir");
const outputDirectory = outputIndex >= 0
  ? path.resolve(process.cwd(), process.argv[outputIndex + 1])
  : defaultOutputDirectory;

const contracts = [
  {
    output: "runner-v2.ts",
    source: "runner/v2/*.schema.json",
    schemas: ["runner/v2/result.schema.json", "runner/v2/progress.schema.json", "runner/v2/event.schema.json"],
  },
  { output: "meeting-job-v1.ts", source: "meeting-job/v1/meeting-job.schema.json", schemas: ["meeting-job/v1/meeting-job.schema.json"] },
  { output: "settings-v1.ts", source: "settings/v1/settings.schema.json", schemas: ["settings/v1/settings.schema.json"] },
  { output: "ai-v1.ts", source: "ai/v1/ai.schema.json", schemas: ["ai/v1/ai.schema.json"] },
  { output: "runtime-v1.ts", source: "runtime/v1/runtime.schema.json", schemas: ["runtime/v1/runtime.schema.json"] },
];

await mkdir(outputDirectory, { recursive: true });
for (const contract of contracts) {
  const generated = [];
  for (const schema of contract.schemas) {
    generated.push(await compileFromFile(path.join(schemaBase, schema), {
      bannerComment: "",
      cwd: path.dirname(path.join(schemaBase, schema)),
      style: { singleQuote: false },
      unreachableDefinitions: true,
    }));
  }
  const banner = [
    "// Generated by scripts/generate-contracts.mjs.",
    `// Source: packages/shared-types/schemas/${contract.source}`,
    "// Do not edit by hand.",
    "",
  ].join("\n");
  const outputPath = path.join(outputDirectory, contract.output);
  await writeFile(outputPath, `${banner}${generated.join("\n").trim()}\n`, "utf8");
  console.log(`Generated ${path.relative(repositoryRoot, outputPath)}`);
}
